#!/usr/bin/env python3
"""Write the demo proxies' policy: the bundled policy with the winning switches.

The 8-combination experiment chose session memory + classifier + allowlist
(docs/results/protection-combinations.md); #212 added user-named destinations,
so a send goes only to listed destinations the user typed. Both demo proxies
run that policy; only their memory (ROUTER_MODE) differs. The allowlist also
needs this clone's demo recipient, which lives in deploy/.env, so the file is
generated rather than committed:

    deploy/policy.yaml + DEMO_RECIPIENT  ->  deploy/policy.demo.yaml (git-ignored)

The demo attack address (a plus-address of the recipient, see
demo/mcp_server.attack_recipient) is deliberately not added, so the gateway
holds sends to it. The recipient is the operator's own mailbox, so it is also
added to own_destinations: "email me" counts as naming it (#212).

`make demo-dual-up` runs this before starting the proxies.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from router.allowlist import Allowlist  # noqa: E402
from router.controls import resolve_controls  # noqa: E402
from router.inventory import Inventory, origin  # noqa: E402
from router.policy import PolicyEngine, load_policy_document  # noqa: E402

SOURCE = REPO_ROOT / "deploy" / "policy.yaml"
TARGET = REPO_ROOT / "deploy" / "policy.demo.yaml"
DEFAULT_DEMO_RECIPIENT = "demo-recipient@example.test"
DEMO_CONTROLS = {"classifier": "on", "allowlist": "on", "user_named": "on"}
# Web pages the demo script fetches (Beat 1: https://httpbin.org/html). Since
# #219 a fetch is checked like a send, so with the allowlist on, an unlisted
# page is held.
DEMO_WEB_PAGES = ("https://httpbin.org/html",)
# The demo tool service's tools, declared (#176). The gateway no longer guesses
# from the name: a tool missing here is held, and a call that contradicts its
# declaration (a local read asked to reach a URL) is blocked. Fixed
# destinations are deploy-time config, never the tool's own metadata: GitHub
# and Gmail are public origins; Jira's comes from JIRA_BASE_URL.
DEMO_TOOLS: dict[str, dict] = {
    "read_file": {"capability": "local-read"},
    "search_knowledge_base": {"capability": "local-read"},
    "list_mcp_resources": {"capability": "local-read"},
    "fetch_url": {"capability": "network-read"},
    "web_search": {"capability": "network-read"},
    "list_emails": {"capability": "network-read", "destination": "https://gmail.googleapis.com"},
    "read_email": {"capability": "network-read", "destination": "https://gmail.googleapis.com"},
    "search_jira": {"capability": "network-read"},
    "get_jira_issue": {"capability": "network-read"},
    "list_github_issues": {"capability": "network-read", "destination": "https://api.github.com"},
    "get_github_issue": {"capability": "network-read", "destination": "https://api.github.com"},
    "send_email": {"capability": "egress"},
    "http_post": {"capability": "egress"},
}
JIRA_TOOLS = ("search_jira", "get_jira_issue")

HEADER = """\
# GENERATED by scripts/demo_policy.py from deploy/policy.yaml; do not edit.
# The demo proxies' policy: the winning switches (classifier, allowlist and
# user_named on), the web pages the demo script fetches, the demo tools
# declared, and this clone's DEMO_RECIPIENT added to allowed_destinations and
# own_destinations.
"""


def demo_tools(jira_base_url: str = "") -> dict[str, dict]:
    """The demo inventory, with Jira's origin filled in from deploy-time config."""
    tools = {name: dict(spec) for name, spec in DEMO_TOOLS.items()}
    jira_origin = origin(jira_base_url) if jira_base_url.strip() else None
    if jira_origin:
        for name in JIRA_TOOLS:
            tools[name]["destination"] = jira_origin
    return tools


def demo_policy(document: dict, recipient: str, jira_base_url: str = "") -> dict:
    policy = dict(document)
    policy["controls"] = dict(DEMO_CONTROLS)
    policy["tools"] = demo_tools(jira_base_url)
    destinations = list(policy.get("allowed_destinations") or [])
    for page in DEMO_WEB_PAGES:
        if page not in destinations:
            destinations.append(page)
    if recipient not in (str(entry).lower() for entry in destinations):
        destinations.append(recipient)
    policy["allowed_destinations"] = destinations
    own = list(policy.get("own_destinations") or [])
    if recipient not in (str(entry).lower() for entry in own):
        own.append(recipient)
    policy["own_destinations"] = own
    return policy


def validate(policy: dict) -> None:
    """Fail here, not in the proxy: the router checks the same things at startup."""
    PolicyEngine.from_mapping(policy)
    Allowlist.from_entries(policy["allowed_destinations"])
    Allowlist.from_entries(policy.get("own_destinations") or [])
    inventory = Inventory.from_mapping(policy)
    if inventory is None or len(inventory) == 0:
        raise ValueError("demo policy must declare the demo tools")
    controls = resolve_controls(policy, env="")
    if not (controls.classifier and controls.allowlist and controls.user_named):
        raise ValueError(f"demo policy must turn every switch on, got {controls.label()}")


def main() -> int:
    recipient = os.environ.get("DEMO_RECIPIENT", DEFAULT_DEMO_RECIPIENT).strip().lower()
    jira_base_url = os.environ.get("JIRA_BASE_URL", "")
    policy = demo_policy(load_policy_document(SOURCE), recipient, jira_base_url)
    try:
        validate(policy)
    except ValueError as exc:
        print(f"demo policy is invalid: {exc}", file=sys.stderr)
        return 2
    TARGET.write_text(HEADER + yaml.safe_dump(policy, sort_keys=False, allow_unicode=True))
    print(
        f"wrote {TARGET.relative_to(REPO_ROOT)} (allowlist and user_named on; recipient {recipient})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
